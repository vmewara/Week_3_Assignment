import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

data=pd.read_csv("sales_data.csv")
df=pd.DataFrame(data)
df

df.head(5)

plt.barh(df['product'],df['revenue'])
plt.xlabel('Revenue')
plt.ylabel('Product')

plt.show()

plt.bar(df['category'],df['discount'])

plt.xlabel('category')
plt.ylabel('discount')

plt.show()

category_revenue = df.groupby('category')['profit'].sum()
plt.pie(category_revenue, labels=category_revenue.index, autopct='%1.1f%%')
plt.title('profit by category')
plt.show()

sns.lineplot(data=df, x='order_date', y='revenue')
plt.title("Revenue by Date")
plt.xlabel("Date")
plt.ylabel("Revenue")
plt.show()

sns.boxplot(data=df,x='revenue')

sns.histplot(x='quantity', y='unit_price',hue='discount',data=df)
plt.xlabel('"Quantity')
plt.ylabel('Unit_Price7')
plt.show()

sns.violinplot(data=df, x="region", y="profit")
plt.xlabel("Region")
plt.ylabel("Profit")
plt.title("Region vs Profit — Violin Plot")

plt.show()

sns.histplot(x="revenue",data=df,bins=10,kde=True)
plt.xlabel("Revenue")
plt.ylabel("Frequency")
plt.show()

